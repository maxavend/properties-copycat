// Renders the official Figma icons from @create-figma-plugin/ui to SVG strings once,
// so the UI ships plain markup instead of Preact. Run with `npm run icons`.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { h } from 'preact';
import { renderToString } from 'preact-render-to-string';

const ICONS = {
  instance: 'icon-16/icon-instance-16.js',
  component: 'icon-16/icon-component-16.js',
  componentSet: 'icon-16/icon-component-set-16.js',
  frame: 'icon-16/icon-frame-16.js',
  text: 'icon-16/icon-text-16.js'
};

const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve('@create-figma-plugin/ui')), 'icons');

const entries = [];
for (const [name, file] of Object.entries(ICONS)) {
  const module = await import(pathToFileURL(join(iconsDir, file)).href);
  const Icon = Object.values(module)[0];
  // createIcon wraps the SVG in a <div>; keep only the SVG
  const svg = renderToString(h(Icon, {})).match(/<svg[\s\S]*<\/svg>/)[0]
    .replace('<svg', '<svg aria-hidden="true" focusable="false"');
  entries.push(`  ${name}: '${svg}'`);
}

const out = `// Generated by scripts/extract-icons.mjs from @create-figma-plugin/ui. Do not edit.
export const icons = {
${entries.join(',\n')}
};
`;
writeFileSync(new URL('../ui/icons.js', import.meta.url), out);
console.log(`ui/icons.js: ${entries.length} icons`);
